#!/usr/bin/env node
/**
 * Regenerate types/database.types.ts from Postgres (Supabase).
 *
 * Requires one of:
 *   SUPABASE_DB_URL — direct Postgres URL (self-hosted or Cloud)
 *   SUPABASE_ACCESS_TOKEN + SUPABASE_URL — Supabase Cloud project ref
 *   npm run db:types -- --local — local `supabase start` stack
 */
import { spawnSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outPath = join(root, 'types', 'database.types.ts')

function loadEnvFile(relPath) {
  const path = join(root, relPath)
  if (!existsSync(path)) return
  for (const line of readFileSync(path, 'utf8').split('\n')) {
    const trimmed = line.trim()
    if (!trimmed || trimmed.startsWith('#')) continue
    const eq = trimmed.indexOf('=')
    if (eq <= 0) continue
    const key = trimmed.slice(0, eq)
    let val = trimmed.slice(eq + 1)
    if (
      (val.startsWith('"') && val.endsWith('"'))
      || (val.startsWith("'") && val.endsWith("'"))
    ) {
      val = val.slice(1, -1)
    }
    if (!(key in process.env)) process.env[key] = val
  }
}

loadEnvFile('.env')
loadEnvFile('.env.local')

function runSupabase(args) {
  const localBin = join(root, 'node_modules', 'supabase', 'bin', 'supabase')
  const useLocalBin = existsSync(localBin)
  const cmd = useLocalBin ? localBin : 'npx'
  const cmdArgs = useLocalBin ? args : ['supabase', ...args]
  const result = spawnSync(cmd, cmdArgs, {
    cwd: root,
    encoding: 'utf8',
    env: process.env,
  })
  if (result.status !== 0) {
    process.stderr.write(result.stderr || result.stdout || 'supabase gen types failed\n')
    process.exit(result.status ?? 1)
  }
  return result.stdout
}

function projectRefFromSupabaseUrl(url) {
  const match = url.match(/https:\/\/([^.]+)\.supabase\.co/)
  return match?.[1] ?? null
}

const useLocal = process.argv.includes('--local')
let types = ''

if (useLocal) {
  types = runSupabase(['gen', 'types', 'typescript', '--local'])
} else if (process.env.SUPABASE_DB_URL) {
  types = runSupabase(['gen', 'types', 'typescript', '--db-url', process.env.SUPABASE_DB_URL])
} else {
  const ref = projectRefFromSupabaseUrl(process.env.SUPABASE_URL ?? '')
  if (ref && process.env.SUPABASE_ACCESS_TOKEN) {
    types = runSupabase(['gen', 'types', 'typescript', '--project-id', ref])
  } else {
    console.error(`Cannot generate database types. Configure one of:

  SUPABASE_DB_URL=postgresql://...
    (Supabase Dashboard → Project Settings → Database, or self-hosted Postgres)

  SUPABASE_ACCESS_TOKEN=... and SUPABASE_URL=https://<ref>.supabase.co
    (or run: npx supabase login)

  npm run db:types -- --local
    (requires \`supabase start\` with Docker)
`)
    process.exit(1)
  }
}

mkdirSync(dirname(outPath), { recursive: true })
const banner = '// Generated by `npm run db:types`. Do not edit manually.\n\n'
writeFileSync(outPath, banner + types)
console.log(`Wrote ${outPath} (${types.split('\n').length} lines)`)
